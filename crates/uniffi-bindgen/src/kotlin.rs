use std::ffi::OsString;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

pub fn output_directory(arguments: &[OsString]) -> Option<PathBuf> {
    if arguments.first()?.to_str()? != "generate" {
        return None;
    }
    let mut kotlin = false;
    let mut output = None;
    let mut arguments = arguments.iter().skip(1);
    while let Some(argument) = arguments.next() {
        let Some(argument) = argument.to_str() else {
            continue;
        };
        match argument {
            "--language" | "-l" => {
                kotlin |= arguments.next().is_some_and(|value| value == "kotlin")
            }
            "--out-dir" | "-o" => output = arguments.next().map(PathBuf::from),
            _ => {
                kotlin |= argument == "--language=kotlin" || argument == "-lkotlin";
                if let Some(path) = argument.strip_prefix("--out-dir=") {
                    output = Some(PathBuf::from(path));
                } else if let Some(path) =
                    argument.strip_prefix("-o").filter(|path| !path.is_empty())
                {
                    output = Some(PathBuf::from(path));
                }
            }
        }
    }
    kotlin.then_some(output).flatten()
}

pub fn fix_external_error_buffers(directory: &Path) -> io::Result<usize> {
    let mut changed = 0;
    for entry in fs::read_dir(directory)? {
        let entry = entry?;
        let file_type = entry.file_type()?;
        if file_type.is_dir() {
            changed += fix_external_error_buffers(&entry.path())?;
        } else if file_type.is_file() && entry.path().extension().is_some_and(|value| value == "kt")
        {
            let source = fs::read_to_string(entry.path())?;
            let fixed = external_error_buffers(&source);
            let fixed = integrity_checksum_returns(&fixed);
            if source != fixed {
                fs::write(entry.path(), fixed)?;
                changed += 1;
            }
        }
    }
    Ok(changed)
}

// UniFFI 0.32 lowers external callback errors into a wrapper owned by the
// defining component. Callback status needs the wrapper of the calling component.
// Transfer its descriptor without copying or freeing the Rust allocation;
// Rust takes ownership of that same allocation when it consumes the status.
fn external_error_buffers(source: &str) -> String {
    let header = source.lines().next().unwrap_or_default();
    if !header.contains("autogenerated") || !header.contains("uniffi") {
        return source.to_string();
    }
    let mut fixed = source.to_string();
    for (exception, converter) in [
        ("HostException", "FfiConverterTypeHostError"),
        ("ViewerException", "FfiConverterTypeViewerError"),
    ] {
        let imported = source.lines().any(|line| {
            let line = line.trim();
            line.starts_with("import ") && line.ends_with(&format!(".{converter}"))
        });
        if imported {
            let original = format!("{{ e: {exception} -> {converter}.lower(e) }}");
            let replacement = format!(
                "{{ e: {exception} -> {converter}.lower(e).let {{ RustBuffer.create(it.capacity.toULong(), it.len.toULong(), it.data) }} }}"
            );
            fixed = fixed.replace(&original, &replacement);
        }
    }
    fixed
}

// Checksum exports return u16. Give JNA the native width and compare its
// unsigned bit pattern; upper register bits are not part of that return ABI.
fn integrity_checksum_returns(source: &str) -> String {
    let header = source.lines().next().unwrap_or_default();
    if !header.contains("autogenerated") || !header.contains("uniffi") {
        return source.to_string();
    }
    let mut integrity_object = false;
    let mut checksum_declaration = false;
    let mut checksum_assertions = false;
    let mut fixed = String::with_capacity(source.len());
    for line in source.split_inclusive("\n") {
        let trimmed = line.trim();
        if trimmed == "internal object IntegrityCheckingUniffiLib {" {
            integrity_object = true;
        } else if trimmed == "internal object UniffiLib {" {
            integrity_object = false;
            checksum_declaration = false;
        }
        if integrity_object && trimmed.starts_with("external fun ") {
            checksum_declaration =
                trimmed.starts_with("external fun uniffi_") && trimmed.contains("_checksum_");
        }
        if trimmed.starts_with("private fun uniffiCheckApiChecksums(") {
            checksum_assertions = true;
        } else if checksum_assertions && line.starts_with("}") {
            checksum_assertions = false;
        }
        let adapted = if checksum_declaration && line.contains("): ") {
            checksum_declaration = false;
            line.replacen("): Int", "): Short", 1)
        } else if checksum_assertions
            && trimmed.starts_with("if (lib.uniffi_")
            && trimmed.contains("_checksum_")
        {
            line.replacen("() !=", "().toInt().and(0xffff) !=", 1)
        } else {
            line.to_string()
        };
        fixed.push_str(&adapted);
    }
    fixed
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn external_callback_errors_transfer_the_allocation_descriptor() {
        for (exception, converter) in [
            ("HostException", "FfiConverterTypeHostError"),
            ("ViewerException", "FfiConverterTypeViewerError"),
        ] {
            let source = format!(
                "// autogenerated by uniffi\nimport uniffi.epdf_ffi.{converter}\n{{ e: {exception} -> {converter}.lower(e) }}"
            );
            let fixed = external_error_buffers(&source);
            let fixed = integrity_checksum_returns(&fixed);
            assert!(
                fixed.contains(
                    "RustBuffer.create(it.capacity.toULong(), it.len.toULong(), it.data)"
                )
            );
            assert_eq!(external_error_buffers(&fixed), fixed);
        }
    }

    #[test]
    fn local_error_callbacks_keep_their_component_buffer() {
        let source = "// autogenerated by uniffi\n{ e: HostException -> FfiConverterTypeHostError.lower(e) }";
        assert_eq!(external_error_buffers(source), source);
        let handwritten = "import uniffi.epdf_ffi.FfiConverterTypeHostError\n{ e: HostException -> FfiConverterTypeHostError.lower(e) }";
        assert_eq!(external_error_buffers(handwritten), handwritten);
    }

    #[test]
    fn output_directory_is_limited_to_kotlin_generation() {
        let args = |values: &[&str]| values.iter().map(OsString::from).collect::<Vec<_>>();
        assert_eq!(
            output_directory(&args(&[
                "generate",
                "--language",
                "kotlin",
                "--out-dir",
                "/tmp/generated"
            ])),
            Some(PathBuf::from("/tmp/generated"))
        );
        assert_eq!(
            output_directory(&args(&["generate", "--language=swift", "--out-dir=/tmp/generated"])),
            None
        );
        assert_eq!(
            output_directory(&args(&["generate", "-lkotlin", "-o/tmp/generated"])),
            Some(PathBuf::from("/tmp/generated"))
        );
        assert_eq!(
            output_directory(&args(&[
                "pipeline",
                "--language",
                "kotlin",
                "--out-dir",
                "/tmp/generated"
            ])),
            None
        );
    }
    #[test]
    fn integrity_checksums_keep_the_native_width_and_all_integrity_assertions() {
        let source = "// autogenerated by uniffi\ninternal object IntegrityCheckingUniffiLib {\n    external fun ffi_example_uniffi_contract_version(): Int\n    external fun uniffi_example_checksum_method_cancel(\n    ): Int\n}\ninternal object UniffiLib {\n    external fun uniffi_example_fn_func_checksum_value(): Int\n}\nprivate fun uniffiCheckApiChecksums(lib: IntegrityCheckingUniffiLib) {\n    if (lib.uniffi_example_checksum_method_cancel() != 34807) {\n        throw RuntimeException(\"mismatch\")\n    }\n}\n";
        let fixed = integrity_checksum_returns(source);
        assert!(fixed.contains("checksum_method_cancel(\n    ): Short"));
        assert!(fixed.contains("checksum_method_cancel().toInt().and(0xffff) != 34807"));
        assert!(fixed.contains("throw RuntimeException(\"mismatch\")"));
        assert!(fixed.contains("ffi_example_uniffi_contract_version(): Int"));
        assert!(fixed.contains("uniffi_example_fn_func_checksum_value(): Int"));
        assert_eq!(integrity_checksum_returns(&fixed), fixed);
        let handwritten = source.replacen("// autogenerated by uniffi\n", "", 1);
        assert_eq!(integrity_checksum_returns(&handwritten), handwritten);
    }
}
