//! Page rotation is normalized away before any coordinate leaves the engine.
//!
//! `multiplatform-plan.md` is explicit that Rust "must not call `FPDF_LoadPage`
//! itself: it would bypass normalized rotation", and web's
//! `PagePtrPool.acquire` loads through
//! `EPDFDoc_LoadPageByObjectNumberNormalized` so that render, text, geometry
//! and annotation coordinates all share one space.
//!
//! This went untested for the whole port because no fixture in the repository
//! set `/Rotate` at all, on either side. `rotated_pages.pdf` is four pages with
//! identical content at 0, 90, 180 and 270 degrees, generated by
//! `tooling/engine-conformance/fixtures/generate.mjs`. Under the normalized
//! loader all four are indistinguishable; under `FPDF_LoadPage` the quarter
//! turns report 792x612 instead of 612x792 and move their text to match.

use epdf_engine::access::{DocumentAccess, OwnedDocument, PageAccess};
use epdf_engine::identity::PageObjectNumber;
use pdfium::{Document, Library};

fn document() -> OwnedDocument {
    let path = test_support::workspace_root()
        .join("tooling/engine-conformance/fixtures/rotated_pages.pdf");
    let bytes = std::fs::read(&path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    OwnedDocument::new(
        Document::from_bytes(Library::acquire(), &bytes, None).expect("open rotated_pages.pdf"),
    )
    .expect("index rotated_pages.pdf")
}

/// The four pages, in `/Rotate` order: 0, 90, 180, 270.
fn page_numbers(document: &OwnedDocument) -> Vec<PageObjectNumber> {
    (0..document.page_count())
        .map(|index| {
            let number = document.document().page(index).expect("page").object_number();
            PageObjectNumber::new(number).expect("object number")
        })
        .collect()
}

#[test]
fn every_rotation_reports_the_same_page_size() {
    let document = document();
    let numbers = page_numbers(&document);
    assert_eq!(numbers.len(), 4, "the fixture has one page per quarter turn");

    let sizes: Vec<(f32, f32)> = numbers
        .iter()
        .map(|number| {
            let page = document.page(*number).expect("load page");
            let view = page.view();
            (view.width(), view.height())
        })
        .collect();

    // 612x792 four times. Loading by index instead gives 792x612 for the
    // quarter turns, which is the regression this exists to catch.
    for (index, size) in sizes.iter().enumerate() {
        assert_eq!(
            *size,
            (612.0, 792.0),
            "page {index} reports {size:?}; rotation was not normalized",
        );
    }
}

#[test]
fn every_rotation_renders_the_same_pixels() {
    // Size alone would pass for /Rotate 180, which does not swap the axes, so
    // the raster is what separates a normalized load from a lucky one.
    //
    // Geometry deliberately is not the check here. PDFium reports text
    // coordinates in unrotated user space whatever `/Rotate` says, so a
    // geometry comparison passes under both loaders and would be a test that
    // looks like coverage without being any.
    let document = document();
    let numbers = page_numbers(&document);

    let rasters: Vec<(u32, u32, Vec<u8>)> = numbers
        .iter()
        .map(|number| {
            let page = document.page(*number).expect("load page");
            let view = page.view();
            let bitmap = view.render_bgra(306, 396).expect("render");
            (bitmap.width, bitmap.height, bitmap.bgra)
        })
        .collect();

    let (width, height, first) = &rasters[0];
    assert!(
        first.iter().any(|byte| *byte != first[0]),
        "the unrotated page rendered a flat image, so this test proves nothing",
    );
    for (index, (w, h, pixels)) in rasters.iter().enumerate().skip(1) {
        assert_eq!((w, h), (width, height), "page {index} rendered at a different size");
        assert_eq!(
            pixels, first,
            "page {index} rendered differently from the unrotated page after normalization",
        );
    }
}

#[test]
fn the_listing_in_page_space_does_not_turn_with_the_page() {
    // Page space ignores `/Rotate`: the 90-degree page still reads 612 by
    // 792, its boxes are not turned, and only `rotation` says it turns.
    use epdf_engine::cancel::CancelToken;
    use epdf_engine::features::pages::list_pages;
    use epdf_engine::geom::{PageRect, PdfRotation, PdfSize};
    use epdf_engine::page_space::pages::page_list_of;

    let document = document();
    let read = list_pages(document.document(), &CancelToken::never()).expect("list");
    let listed = page_list_of(read).expect("in page space");
    let rotations: Vec<PdfRotation> = listed.pages.iter().map(|p| p.rotation).collect();
    assert_eq!(
        rotations,
        [
            PdfRotation::None,
            PdfRotation::Clockwise90,
            PdfRotation::Clockwise180,
            PdfRotation::Clockwise270
        ]
    );
    for page in &listed.pages {
        assert_eq!(page.size, PdfSize { width: 612.0, height: 792.0 }, "page {}", page.index);
        let upright = PageRect { x: 0.0, y: 0.0, width: 612.0, height: 792.0 };
        for b in
            [page.boxes.media, page.boxes.crop, page.boxes.bleed, page.boxes.trim, page.boxes.art]
        {
            assert_eq!(b, upright, "page {}", page.index);
        }
    }
}
