//! Two jobs.
//!
//! The rpath, re-emitted for this crate's own test binaries.
//! `pdfium-sys` emits `-Wl,-rpath,...` for the crate that links libembedpdf,
//! but Cargo does not propagate `cargo:rustc-link-arg` to a dependent
//! package's bin and test targets: only `rustc-link-lib` and
//! `rustc-link-search` are transitive. Every crate that depends on `pdfium`
//! and builds its own binaries needs this line, or its tests link and then
//! fail at load with `Library not loaded: @rpath/libembedpdf.dylib`.
//!
//! The last-resort font: `FontRegistrar` registers
//! `packages/core/fonts/src/last-resort.generated.ts`'s program on every
//! thread. That generated file is the one copy of the program; this script
//! decodes its base64 into `$OUT_DIR/last-resort.ttf` and writes its hash to
//! `$OUT_DIR/last_resort.rs`, so the Rust and the TypeScript register the same
//! bytes. It reads the generator's exact layout and panics on anything else,
//! rather than guess. (`epdf-fonts` reads the standard faces the same way; a
//! dependency on it would be a cycle through its harness.)

use std::path::PathBuf;

fn main() {
    build_support::emit_rpath_only();

    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let generated = manifest
        .ancestors()
        .map(|dir| dir.join("packages/core/fonts/src/last-resort.generated.ts"))
        .find(|file| file.is_file())
        .unwrap_or_else(|| {
            panic!(
                "no packages/core/fonts/src/last-resort.generated.ts above {}",
                manifest.display()
            )
        });
    println!("cargo:rerun-if-changed={}", generated.display());
    let text = std::fs::read_to_string(&generated)
        .unwrap_or_else(|e| panic!("read {}: {e}", generated.display()));
    let constant = |name: &str| {
        let prefix = format!("export const {name} = '");
        text.lines()
            .find_map(|line| line.strip_prefix(prefix.as_str())?.strip_suffix("';"))
            .unwrap_or_else(|| panic!("last-resort.generated.ts: no {name}"))
            .to_string()
    };
    let hash = constant("LAST_RESORT_HASH");
    assert!(
        hash.len() == 64 && hash.bytes().all(|b| b.is_ascii_hexdigit()),
        "LAST_RESORT_HASH: not a SHA-256"
    );
    let program = constant("LAST_RESORT_PROGRAM");
    let alphabet = |b: u8| b.is_ascii_alphanumeric() || matches!(b, b'+' | b'/' | b'=');
    assert!(
        program.len().is_multiple_of(4) && program.bytes().all(alphabet),
        "LAST_RESORT_PROGRAM: not padded base64"
    );

    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    std::fs::write(out.join("last-resort.ttf"), decode_base64(&program))
        .expect("write last-resort.ttf");
    std::fs::write(
        out.join("last_resort.rs"),
        format!(
            "// Generated by build.rs from packages/core/fonts/src/last-resort.generated.ts. \
             Don't edit.\n\n\
             /// `LAST_RESORT_HASH`: the SHA-256 of [`LAST_RESORT_PROGRAM`].\n\
             pub const LAST_RESORT_HASH: &str = \"{hash}\";\n\n\
             /// The last-resort program: a box for every code point.\n\
             pub static LAST_RESORT_PROGRAM: &[u8] = \
             include_bytes!(concat!(env!(\"OUT_DIR\"), \"/last-resort.ttf\"));\n"
        ),
    )
    .expect("write last_resort.rs");
}

/// `decodeBase64(text)`, as `packages/core/fonts/src/base64.ts` decodes it:
/// padded base64, which `main` has checked.
fn decode_base64(text: &str) -> Vec<u8> {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let value = |byte: u8| ALPHABET.iter().position(|&c| c == byte).map_or(0, |at| at as u32);
    let padding = text.bytes().rev().take_while(|&b| b == b'=').count().min(2);
    let length = (text.len() / 4 * 3).saturating_sub(padding);
    let mut out = Vec::with_capacity(length);
    for group in text.as_bytes().chunks(4) {
        let at = |index: usize| group.get(index).copied().map_or(0, value);
        let chunk = (at(0) << 18) | (at(1) << 12) | (at(2) << 6) | at(3);
        for byte in [chunk >> 16, (chunk >> 8) & 0xff, chunk & 0xff] {
            if out.len() < length {
                out.push(byte as u8);
            }
        }
    }
    out
}
