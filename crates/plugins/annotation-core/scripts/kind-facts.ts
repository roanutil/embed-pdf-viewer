/**
 * Writes `src/engine/kind_facts.rs` from engine-core's generated kind facts
 * and its defaults table, so the Rust predictor reads the same tables:
 *
 *   pnpm exec tsx crates/plugins/annotation-core/scripts/kind-facts.ts \
 *     > crates/plugins/annotation-core/src/engine/kind_facts.rs
 *
 * Run it again whenever `packages/engine/core/src/annotation/kind-facts.generated.ts`
 * or `annotation/defaults.ts` changes.
 */
import { ANNOTATION_KIND_FACTS } from '../../../../packages/engine/core/src/annotation/kind-facts.generated';
import { ANNOTATION_DEFAULTS } from '../../../../packages/engine/core/src/annotation/defaults';

const owner = (o: string) =>
  ({ data: 'Data', attribution: 'Attribution', engine: 'Engine', preserved: 'Preserved' })[o];
const space = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

const out: string[] = [];
out.push('//! Generated by `scripts/kind-facts.ts` from engine-core\'s');
out.push('//! `annotation/kind-facts.generated.ts` and `annotation/defaults.ts`. Not');
out.push('//! edited by hand: rerun the script when either changes.');
out.push('');
out.push('use super::facts::{FieldOwner, FieldSpace, KindFacts};');
out.push('');
out.push('/// Each kind\'s facts, in the engine\'s catalog order.');
out.push('pub const KIND_FACTS: &[(&str, KindFacts)] = &[');
for (const [subtype, facts] of Object.entries(ANNOTATION_KIND_FACTS)) {
  out.push(`    (`);
  out.push(`        ${JSON.stringify(subtype)},`);
  out.push(`        KindFacts {`);
  out.push(`            owners: &[`);
  for (const [name, o] of Object.entries(facts.owners))
    out.push(`                (${JSON.stringify(name)}, FieldOwner::${owner(o)}),`);
  out.push(`            ],`);
  out.push(`            read_back: &[${facts.readBack.map((n) => JSON.stringify(n)).join(', ')}],`);
  out.push(`            colors: &[${facts.colors.map((n) => JSON.stringify(n)).join(', ')}],`);
  out.push(`            spaces: &[`);
  for (const [name, s] of Object.entries(facts.spaces))
    out.push(`                (${JSON.stringify(name)}, FieldSpace::${space(s)}),`);
  out.push(`            ],`);
  out.push(`        },`);
  out.push(`    ),`);
}
out.push('];');
out.push('');
out.push('/// `ANNOTATION_DEFAULTS`, each kind\'s members in the order the table spreads them.');
out.push(`pub const DEFAULTS_JSON: &str = r##"${JSON.stringify(ANNOTATION_DEFAULTS)}"##;`);
console.log(out.join('\n'));
